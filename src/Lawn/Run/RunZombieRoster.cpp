bool RunZombieAllowedOnLevel(ZombieType theZombieType, int theRunLevelIndex, bool theZombotany)
{
	int aType = (int)theZombieType;
	if (aType < 0 || aType >= (int)NUM_ZOMBIE_TYPES) return false;

	int aIndex = theRunLevelIndex;
	if (aIndex < 0) aIndex = 0;
	if (aIndex >= RunState::RUN_LEVEL_COUNT) aIndex = RunState::RUN_LEVEL_COUNT - 1;

	unsigned long long aMask = RUN_ZOMBIE_ROSTER[aIndex / RunState::RUN_LEVELS_PER_SCENE][aIndex % RunState::RUN_LEVELS_PER_SCENE];

	// @pvz-online: 植物僵尸开关（2026-10-09，批 C 的 mZombotany 在这里消费，MOD_BUILD 35）：
	// 开了就把基准五种 ZomBotany 及其铁门版（2026-10-11 加入，共十种）OR 进当关名单——
	// 查询层放行、表本体不动，关 = 逐位复原（波表与关前一致）。十种 def pickWeight 全 >0；
	// 原版 ZomBotany 关卡已裁、它们 startingLevel=99，除这里外没有入口。行/场硬约束照旧在
	// 名单之外生效（ZomBotany 用普僵身体、无水生属性，天然只落陆行）。
	if (theZombotany)
	{
		aMask |= RZ(ZOMBIE_PEA_HEAD) | RZ(ZOMBIE_WALLNUT_HEAD) | RZ(ZOMBIE_JALAPENO_HEAD) | RZ(ZOMBIE_GATLING_HEAD) | RZ(ZOMBIE_SQUASH_HEAD) |
			0ULL; // No armored plant-head types until their implementation is ported.
	}

	return (aMask & (1ULL << aType)) != 0ULL;
}

// Ported from PC 7a756a2. New armored types 34-41 stay filtered until their behavior/cache port.
int RunZombieWeight(ZombieType type)
{
    if (GetZombieDefinition(type).mPickWeight <= 0) return 0;
    if (type == ZOMBIE_BALLOON || type == ZOMBIE_JALAPENO_HEAD || type == ZOMBIE_GATLING_HEAD || type == ZOMBIE_SQUASH_HEAD) return 250;
    if (type == ZOMBIE_WALLNUT_HEAD) return 500;
    return 1000;
}
int RunLevelIndexForEngineLevel(int theLevel)
{
	// 拿 LevelForIndex 反查、不另写一份除模公式：正反两个方向永远同步，
	// 免得公式改一处忘一处。
	for (int i = 0; i < RunState::RUN_LEVEL_COUNT; i++)
	{
		if (RunState::LevelForIndex(i) == theLevel) return i;
	}
	// 表外的关号（旧构建混搭、迷你游戏之类）一律当第 1 关：宁可出基本怪，也别读穿名单。
	return 0;
}

