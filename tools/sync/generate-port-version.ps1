param([switch]$Check)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$baseline = Get-Content -LiteralPath "$projectRoot/docs/compatibility/pc-source-baseline.json" -Raw | ConvertFrom-Json
if ($baseline.pcCommit -notmatch '^[0-9a-f]{40}$') { throw 'Invalid pinned PC commit.' }
$protocol = Get-Content -LiteralPath "$projectRoot/src/Lawn/Online/NetProtocol.h" -Raw
foreach ($entry in @(@('MOD_BUILD', $baseline.pcModBuild), @('PROTOCOL_VERSION', $baseline.pcProtocolVersion))) {
    $match = [regex]::Match($protocol, "const\s+uint16_t\s+$($entry[0])\s*=\s*(\d+)\s*;")
    if (!$match.Success -or [int]$match.Groups[1].Value -ne [int]$entry[1]) {
        throw "Pinned metadata disagrees with NetProtocol::$($entry[0]); port the matching source before advancing the baseline."
    }
}
$ready = if ($baseline.onlineGameReady) { 'true' } else { 'false' }
$text = @"
#pragma once
// Generated by tools/sync/generate-port-version.ps1 from the reviewed source baseline.
inline constexpr const char* PVZ_ANDROID_PC_COMMIT = "$($baseline.pcCommit)";
inline constexpr unsigned PVZ_ANDROID_PC_MOD_BUILD = $($baseline.pcModBuild);
inline constexpr unsigned PVZ_ANDROID_PC_PROTOCOL_VERSION = $($baseline.pcProtocolVersion);
inline constexpr bool PVZ_ANDROID_ONLINE_GAME_READY = $ready;
"@
$text = ($text -replace "`r`n", "`n") + "`n"
$outputPath = "$projectRoot/src/Lawn/Run/PortVersion.h"
if ($Check) {
    if (!(Test-Path -LiteralPath $outputPath) -or [IO.File]::ReadAllText($outputPath) -cne $text) {
        throw 'PortVersion.h is stale; regenerate it from the reviewed baseline.'
    }
    Write-Output 'Pinned PC metadata, protocol constants and generated version header match.'
} else {
    [IO.File]::WriteAllText($outputPath, $text, [Text.UTF8Encoding]::new($false))
    Write-Output "Generated $outputPath"
}
